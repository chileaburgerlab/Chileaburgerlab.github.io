/* CHILEA BURGER LAB — service worker: la página abre sin internet tras la primera visita */
const CACHE = "chilea-v1";
const ASSETS = [
  "./", "./index.html", "./manifest.json",
  "./logo.png", "./logo-ar.png",
  "./icon-192.png", "./icon-512.png", "./icon-maskable.png", "./apple-touch-icon.png",
  "./admin.html"
];

self.addEventListener("install", e => {
  e.waitUntil(
    caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", e => {
  e.waitUntil(
    caches.keys()
      .then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", e => {
  if (e.request.method !== "GET") return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  /* fotos.json siempre intenta la red primero: las fotos nuevas deben verse */
  if (url.pathname.endsWith("fotos.json")) {
    e.respondWith(
      fetch(e.request)
        .then(res => {
          const copy = res.clone();
          caches.open(CACHE).then(c => c.put(e.request, copy));
          return res;
        })
        .catch(() => caches.match(e.request))
    );
    return;
  }
  e.respondWith(
    caches.match(e.request).then(hit => {
      if (hit) return hit;
      return fetch(e.request).then(res => {
        const copy = res.clone();
        caches.open(CACHE).then(c => c.put(e.request, copy));
        return res;
      }).catch(() => caches.match("./index.html"));
    })
  );
});
